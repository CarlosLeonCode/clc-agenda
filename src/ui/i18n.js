/** Spanish for es-*, English for any other language. */
export function detectLang(env = globalThis) {
  let language = '';
  try {
    language = env.chrome?.i18n?.getUILanguage?.() || env.navigator?.language || '';
  } catch (e) {}
  return /^es\b/i.test(language) ? 'es' : 'en';
}

/** Returns t(key, params): `{name}` placeholders, or functions for counts. */
export function translator(lang) {
  const dict = MESSAGES[lang] || MESSAGES.en;
  return (key, params = {}) => {
    const value = dict[key];
    if (typeof value === 'function') return value(params);
    if (typeof value !== 'string') return key;
    return value.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? ''));
  };
}

